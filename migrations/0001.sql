CREATE TABLE IF NOT EXISTS config(id INTEGER PRIMARY KEY CHECK(id=1), data TEXT);
CREATE TABLE IF NOT EXISTS tickets(id TEXT PRIMARY KEY,name TEXT NOT NULL,phone TEXT,paid INTEGER NOT NULL,created TEXT NOT NULL,used TEXT,cancelled INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,role TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(ip TEXT PRIMARY KEY,n INTEGER NOT NULL,time INTEGER NOT NULL);
